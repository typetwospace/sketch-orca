/// `_Charconv_digits`.
static CHARCONV_DIGITS: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";

/// `_Integer_to_chars` for an unsigned magnitude, after any '-' has been written.
fn integer_digits(buf: &mut [u8], first: usize, mut value: u64, base: u32) -> Res {
    let last = buf.len();
    debug_assert!((2..=36).contains(&base));
    // Enough for base 2.
    let mut tmp = [0u8; 64];
    let mut rnext = tmp.len();
    loop {
        rnext -= 1;
        tmp[rnext] = CHARCONV_DIGITS[(value % u64::from(base)) as usize];
        value /= u64::from(base);
        if value == 0 {
            break;
        }
    }
    let digits_written = tmp.len() - rnext;
    if last - first < digits_written {
        return TOO_LARGE;
    }
    buf[first..first + digits_written].copy_from_slice(&tmp[rnext..]);
    Ok(first + digits_written)
}

/// `std::to_chars(first, last, value, base)` for a signed integer (any width: `int`, `long long`
/// and the narrower ones give the same characters as their value here), base 2 to 36, lowercase
/// letters.
///
/// # Panics
///
/// If `base` is outside [2, 36] (the C++ asserts it).
pub fn to_chars_i64(buf: &mut [u8], value: i64, base: u32) -> Result<usize, Errc> {
    assert!((2..=36).contains(&base), "invalid base in to_chars()");
    let mut first = 0;
    if value < 0 {
        if buf.is_empty() {
            return TOO_LARGE;
        }
        buf[0] = b'-';
        first = 1;
    }
    // The C++ `0 - value` on the unsigned type: the magnitude, i64::MIN included.
    integer_digits(buf, first, value.unsigned_abs(), base)
}

/// `std::to_chars(first, last, value, base)` for an unsigned integer, base 2 to 36.
///
/// # Panics
///
/// If `base` is outside [2, 36] (the C++ asserts it).
pub fn to_chars_u64(buf: &mut [u8], value: u64, base: u32) -> Result<usize, Errc> {
    assert!((2..=36).contains(&base), "invalid base in to_chars()");
    integer_digits(buf, 0, value, base)
}

