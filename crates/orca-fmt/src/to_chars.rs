/// `__DIGIT_TABLE<char>`: the two-digit numbers 00 to 99, two bytes each.
static DIGIT_TABLE: [u8; 200] = {
    let mut t = [0u8; 200];
    let mut i = 0;
    while i < 100 {
        t[2 * i] = b'0' + (i / 10) as u8;
        t[2 * i + 1] = b'0' + (i % 10) as u8;
        i += 1;
    }
    t
};

/// `memcpy(buf + at, __DIGIT_TABLE + c, 2)`.
#[inline]
fn copy2(buf: &mut [u8], at: usize, c: u32) {
    let c = c as usize;
    buf[at] = DIGIT_TABLE[c];
    buf[at + 1] = DIGIT_TABLE[c + 1];
}

/// `__decimalLength9`: the number of decimal digits of a value below 10^9.
#[inline]
fn decimal_length9(v: u32) -> u32 {
    debug_assert!(v < 1_000_000_000);
    if v >= 100_000_000 {
        9
    } else if v >= 10_000_000 {
        8
    } else if v >= 1_000_000 {
        7
    } else if v >= 100_000 {
        6
    } else if v >= 10_000 {
        5
    } else if v >= 1000 {
        4
    } else if v >= 100 {
        3
    } else if v >= 10 {
        2
    } else {
        1
    }
}

/// `__pow5bits`: `e == 0 ? 1 : ceil(log2(5^e))`, for `e` in [0, 3528].
#[inline]
fn pow5bits(e: i32) -> i32 {
    debug_assert!((0..=3528).contains(&e));
    (((e as u32).wrapping_mul(1_217_359) >> 19) + 1) as i32
}

/// `__log10Pow2`: `floor(log10(2^e))`, for `e` in [0, 1650].
#[inline]
fn log10_pow2(e: i32) -> u32 {
    debug_assert!((0..=1650).contains(&e));
    (e as u32).wrapping_mul(78_913) >> 18
}

/// `__log10Pow5`: `floor(log10(5^e))`, for `e` in [0, 2620].
#[inline]
fn log10_pow5(e: i32) -> u32 {
    debug_assert!((0..=2620).contains(&e));
    (e as u32).wrapping_mul(732_923) >> 20
}

const DOUBLE_MANTISSA_BITS: i32 = 52;
const DOUBLE_BIAS: i32 = 1023;
const DOUBLE_POW5_INV_BITCOUNT: i32 = 122;
const DOUBLE_POW5_BITCOUNT: i32 = 121;

/// `__ryu_umul128` (`_umul128` on x64): the low and high halves of the 128-bit product.
#[inline]
fn umul128(a: u64, b: u64) -> (u64, u64) {
    let p = u128::from(a) * u128::from(b);
    (p as u64, (p >> 64) as u64)
}

/// `__ryu_shiftright128` (`__shiftright128` on x64, `shrd`): bits `dist` to `dist + 63` of `hi:lo`.
#[inline]
fn shiftright128(lo: u64, hi: u64, dist: u32) -> u64 {
    debug_assert!(dist < 64);
    (((u128::from(hi) << 64) | u128::from(lo)) >> dist) as u64
}

/// `__div5` (64-bit).
#[inline]
fn div5(x: u64) -> u64 {
    x / 5
}

/// `__div10` (64-bit).
#[inline]
fn div10(x: u64) -> u64 {
    x / 10
}

/// `__div100` (64-bit).
#[inline]
fn div100(x: u64) -> u64 {
    x / 100
}

/// `__div1e8` (64-bit).
#[inline]
fn div1e8(x: u64) -> u64 {
    x / 100_000_000
}

/// `__div1e9` (64-bit).
#[inline]
fn div1e9(x: u64) -> u64 {
    x / 1_000_000_000
}

/// `__pow5Factor` for a 64-bit value: how many times 5 divides `value` (nonzero).
#[inline]
fn pow5_factor64(mut value: u64) -> u32 {
    let mut count = 0;
    loop {
        debug_assert!(value != 0);
        let q = div5(value);
        let r = (value as u32).wrapping_sub(5u32.wrapping_mul(q as u32));
        if r != 0 {
            break;
        }
        value = q;
        count += 1;
    }
    count
}

/// `__multipleOfPowerOf5` (64-bit): whether 5^p divides `value`.
#[inline]
fn multiple_of_power_of5_64(value: u64, p: u32) -> bool {
    pow5_factor64(value) >= p
}

/// `__multipleOfPowerOf2` (64-bit): whether 2^p divides `value`.
#[inline]
fn multiple_of_power_of2_64(value: u64, p: u32) -> bool {
    debug_assert!(value != 0 && p < 64);
    (value & ((1u64 << p) - 1)) == 0
}

/// `__POW10_ADDITIONAL_BITS` of d2fixed.
const POW10_ADDITIONAL_BITS: u32 = 120;

/// `__umul256_hi128_lo64`: the low 64 bits of the high 128 bits of the 256-bit product.
#[inline]
fn umul256_hi128_lo64(a_hi: u64, a_lo: u64, b_hi: u64, b_lo: u64) -> u64 {
    let (_b00_lo, b00_hi) = umul128(a_lo, b_lo);
    let (b01_lo, b01_hi) = umul128(a_lo, b_hi);
    let (b10_lo, b10_hi) = umul128(a_hi, b_lo);
    let (b11_lo, _b11_hi) = umul128(a_hi, b_hi);
    let temp1_lo = b10_lo.wrapping_add(b00_hi);
    let temp1_hi = b10_hi.wrapping_add(u64::from(temp1_lo < b10_lo));
    let temp2_lo = b01_lo.wrapping_add(temp1_lo);
    let temp2_hi = b01_hi.wrapping_add(u64::from(temp2_lo < b01_lo));
    b11_lo.wrapping_add(temp1_hi).wrapping_add(temp2_hi)
}

/// `__uint128_mod1e9`: `v % 10^9` for a 128-bit `v`.
#[inline]
fn uint128_mod1e9(v_hi: u64, v_lo: u64) -> u32 {
    let multiplied = umul256_hi128_lo64(v_hi, v_lo, 0x8970_5F41_36B4_A597, 0x3168_0A88_F895_3031);
    let shifted = (multiplied >> 29) as u32;
    (v_lo as u32).wrapping_sub(1_000_000_000u32.wrapping_mul(shifted))
}

/// `__mulShift_mod1e9`: `(m * mul >> j) % 10^9` for the 192-bit `mul`, `j` in [128, 180].
#[inline]
fn mul_shift_mod1e9(m: u64, mul: &[u64; 3], j: i32) -> u32 {
    let (_low0, high0) = umul128(m, mul[0]);
    let (low1, high1) = umul128(m, mul[1]);
    let (low2, high2) = umul128(m, mul[2]);
    let s0high = low1.wrapping_add(high0);
    let c1 = u64::from(s0high < low1);
    let s1low = low2.wrapping_add(high1).wrapping_add(c1);
    let c2 = u64::from(s1low < low2);
    let s1high = high2.wrapping_add(c2);
    debug_assert!((128..=180).contains(&j));
    let dist = (j - 128) as u32;
    let shiftedhigh = s1high >> dist;
    let shiftedlow = shiftright128(s1low, s1high, dist);
    uint128_mod1e9(shiftedhigh, shiftedlow)
}

/// `__append_n_digits`: the `olength` digits of `digits` at `buf[at..]`.
fn append_n_digits(olength: u32, mut digits: u32, buf: &mut [u8], at: usize) {
    let olength = olength as usize;
    let mut i = 0usize;
    while digits >= 10000 {
        let c = digits % 10000;
        digits /= 10000;
        let c0 = (c % 100) << 1;
        let c1 = (c / 100) << 1;
        copy2(buf, at + olength - i - 2, c0);
        copy2(buf, at + olength - i - 4, c1);
        i += 4;
    }
    if digits >= 100 {
        let c = (digits % 100) << 1;
        digits /= 100;
        copy2(buf, at + olength - i - 2, c);
        i += 2;
    }
    if digits >= 10 {
        let c = digits << 1;
        copy2(buf, at + olength - i - 2, c);
    } else {
        buf[at] = b'0' + digits as u8;
    }
}

/// `__append_d_digits`: the `olength` digits of `digits` with a '.' after the first, at `buf[at..]`.
fn append_d_digits(olength: u32, mut digits: u32, buf: &mut [u8], at: usize) {
    let olength = olength as usize;
    let mut i = 0usize;
    while digits >= 10000 {
        let c = digits % 10000;
        digits /= 10000;
        let c0 = (c % 100) << 1;
        let c1 = (c / 100) << 1;
        copy2(buf, at + olength + 1 - i - 2, c0);
        copy2(buf, at + olength + 1 - i - 4, c1);
        i += 4;
    }
    if digits >= 100 {
        let c = (digits % 100) << 1;
        digits /= 100;
        copy2(buf, at + olength + 1 - i - 2, c);
        // (The C++ adds 2 to i here; it is not read again.)
    }
    if digits >= 10 {
        let c = (digits << 1) as usize;
        buf[at + 2] = DIGIT_TABLE[c + 1];
        buf[at + 1] = b'.';
        buf[at] = DIGIT_TABLE[c];
    } else {
        buf[at + 1] = b'.';
        buf[at] = b'0' + digits as u8;
    }
}

/// `__append_c_digits`: the low `count` digits of `digits`, zero-filled, at `buf[at..]`.
fn append_c_digits(count: u32, mut digits: u32, buf: &mut [u8], at: usize) {
    let count = count as usize;
    let mut i = 0usize;
    // The C++ `i < count - 1`, for the count >= 1 it is called with.
    while i + 1 < count {
        let c = (digits % 100) << 1;
        digits /= 100;
        copy2(buf, at + count - i - 2, c);
        i += 2;
    }
    if i < count {
        buf[at + count - i - 1] = b'0' + (digits % 10) as u8;
    }
}

/// `__append_nine_digits`: `digits` (below 10^9) as nine zero-filled digits at `buf[at..]`.
fn append_nine_digits(mut digits: u32, buf: &mut [u8], at: usize) {
    if digits == 0 {
        buf[at..at + 9].fill(b'0');
        return;
    }
    let mut i = 0usize;
    while i < 5 {
        let c = digits % 10000;
        digits /= 10000;
        let c0 = (c % 100) << 1;
        let c1 = (c / 100) << 1;
        copy2(buf, at + 7 - i, c0);
        copy2(buf, at + 5 - i, c1);
        i += 4;
    }
    buf[at] = b'0' + digits as u8;
}

/// `__indexForExponent`.
#[inline]
fn index_for_exponent(e: u32) -> u32 {
    e.div_ceil(16)
}

/// `__pow10BitsForIndex`.
#[inline]
fn pow10_bits_for_index(idx: u32) -> u32 {
    16 * idx + POW10_ADDITIONAL_BITS
}

/// `__lengthForIndex`: +1 for ceil, +16 for the mantissa, +8 to round up when dividing by 9.
#[inline]
fn length_for_index(idx: u32) -> u32 {
    (log10_pow2(16 * idx as i32) + 1 + 16).div_ceil(9)
}

/// The decoded `double` the d2fixed and d2exp functions start from: `m2 * 2^e2`.
#[inline]
fn decode_d(bits: u64) -> (i32, u64) {
    let ieee_mantissa = bits & ((1u64 << DOUBLE_MANTISSA_BITS) - 1);
    let ieee_exponent = (bits >> DOUBLE_MANTISSA_BITS) as u32;
    if ieee_exponent == 0 {
        (1 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS, ieee_mantissa)
    } else {
        (
            ieee_exponent as i32 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS,
            (1u64 << DOUBLE_MANTISSA_BITS) | ieee_mantissa,
        )
    }
}

/// `__d2fixed_buffered_n`: `d` (not negative) with `precision` digits after the point, `%.*f`.
fn d2fixed_buffered_n(buf: &mut [u8], mut first: usize, d: f64, precision: u32) -> Res {
    let last = buf.len();
    let original_first = first;
    let bits = d.to_bits();

    // Case distinction; exit early for the easy cases.
    if bits == 0 {
        let total_zero_length = 1 + usize::from(precision != 0) + precision as usize;
        if last - first < total_zero_length {
            return TOO_LARGE;
        }
        buf[first] = b'0';
        first += 1;
        if precision > 0 {
            buf[first] = b'.';
            first += 1;
            buf[first..first + precision as usize].fill(b'0');
            first += precision as usize;
        }
        return Ok(first);
    }

    let (e2, m2) = decode_d(bits);

    let mut nonzero = false;
    if e2 >= -52 {
        let idx = if e2 < 0 {
            0
        } else {
            index_for_exponent(e2 as u32)
        };
        let p10bits = pow10_bits_for_index(idx);
        let len = length_for_index(idx) as i32;
        let mut i = len - 1;
        while i >= 0 {
            let j = p10bits.wrapping_sub(e2 as u32);
            let digits = mul_shift_mod1e9(
                m2 << 8,
                &POW10_SPLIT[POW10_OFFSET[idx as usize] as usize + i as usize],
                j as i32 + 8,
            );
            if nonzero {
                if last - first < 9 {
                    return TOO_LARGE;
                }
                append_nine_digits(digits, buf, first);
                first += 9;
            } else if digits != 0 {
                let olength = decimal_length9(digits);
                if last - first < olength as usize {
                    return TOO_LARGE;
                }
                append_n_digits(olength, digits, buf, first);
                first += olength as usize;
                nonzero = true;
            }
            i -= 1;
        }
    }
    if !nonzero {
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'0';
        first += 1;
    }
    if precision > 0 {
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'.';
        first += 1;
    }
    if e2 < 0 {
        let idx = (-e2 / 16) as usize;
        let blocks = precision / 9 + 1;
        // 0 = don't round up; 1 = round up unconditionally; 2 = round up if odd.
        let mut round_up = 0;
        let mut i: u32 = 0;
        let min_block = u32::from(MIN_BLOCK_2[idx]);
        if blocks <= min_block {
            i = blocks;
            if last - first < precision as usize {
                return TOO_LARGE;
            }
            buf[first..first + precision as usize].fill(b'0');
            first += precision as usize;
        } else if i < min_block {
            i = min_block;
            if last - first < 9 * i as usize {
                return TOO_LARGE;
            }
            buf[first..first + 9 * i as usize].fill(b'0');
            first += 9 * i as usize;
        }
        while i < blocks {
            let j = ADDITIONAL_BITS_2 as i32 + (-e2 - 16 * idx as i32);
            let p = u32::from(POW10_OFFSET_2[idx]) + i - min_block;
            if p >= u32::from(POW10_OFFSET_2[idx + 1]) {
                // If the remaining digits are all 0, then we might as well use memset.
                // No rounding required in this case.
                let fill = (precision - 9 * i) as usize;
                if last - first < fill {
                    return TOO_LARGE;
                }
                buf[first..first + fill].fill(b'0');
                first += fill;
                break;
            }
            let mut digits = mul_shift_mod1e9(m2 << 8, &POW10_SPLIT_2[p as usize], j + 8);
            if i < blocks - 1 {
                if last - first < 9 {
                    return TOO_LARGE;
                }
                append_nine_digits(digits, buf, first);
                first += 9;
            } else {
                let maximum = precision - 9 * i;
                let mut last_digit = 0;
                for _ in 0..9 - maximum {
                    last_digit = digits % 10;
                    digits /= 10;
                }
                if last_digit != 5 {
                    round_up = i32::from(last_digit > 5);
                } else {
                    // Is m * 10^(additionalDigits + 1) / 2^(-e2) integer?
                    let required_twos = -e2 - precision as i32 - 1;
                    let trailing_zeros = required_twos <= 0
                        || (required_twos < 60
                            && multiple_of_power_of2_64(m2, required_twos as u32));
                    round_up = if trailing_zeros { 2 } else { 1 };
                }
                if maximum > 0 {
                    if last - first < maximum as usize {
                        return TOO_LARGE;
                    }
                    append_c_digits(maximum, digits, buf, first);
                    first += maximum as usize;
                }
                break;
            }
            i += 1;
        }
        if round_up != 0 {
            let mut round = first;
            let mut dot: Option<usize> = None;
            loop {
                if round == original_first {
                    buf[round] = b'1';
                    if let Some(dot) = dot {
                        buf[dot] = b'0';
                        buf[dot + 1] = b'.';
                    }
                    if first == last {
                        return TOO_LARGE;
                    }
                    buf[first] = b'0';
                    first += 1;
                    break;
                }
                round -= 1;
                let c = buf[round];
                if c == b'.' {
                    dot = Some(round);
                } else if c == b'9' {
                    buf[round] = b'0';
                    round_up = 1;
                } else {
                    if round_up == 1 || !c.is_multiple_of(2) {
                        buf[round] = c + 1;
                    }
                    break;
                }
            }
        }
    } else {
        if last - first < precision as usize {
            return TOO_LARGE;
        }
        buf[first..first + precision as usize].fill(b'0');
        first += precision as usize;
    }
    Ok(first)
}

/// `__d2exp_buffered_n`: `d` (not negative) with `precision` digits after the point, `%.*e`.
fn d2exp_buffered_n(buf: &mut [u8], mut first: usize, d: f64, mut precision: u32) -> Res {
    let last = buf.len();
    let original_first = first;
    let bits = d.to_bits();

    // Case distinction; exit early for the easy cases.
    if bits == 0 {
        let total_zero_length = 1 + usize::from(precision != 0) + precision as usize + 4;
        if last - first < total_zero_length {
            return TOO_LARGE;
        }
        buf[first] = b'0';
        first += 1;
        if precision > 0 {
            buf[first] = b'.';
            first += 1;
            buf[first..first + precision as usize].fill(b'0');
            first += precision as usize;
        }
        buf[first..first + 4].copy_from_slice(b"e+00");
        first += 4;
        return Ok(first);
    }

    let (e2, m2) = decode_d(bits);

    let print_decimal_point = precision > 0;
    precision += 1;
    let mut digits: u32 = 0;
    let mut printed_digits: u32 = 0;
    let mut available_digits: u32 = 0;
    let mut exp: i32 = 0;
    if e2 >= -52 {
        let idx = if e2 < 0 {
            0
        } else {
            index_for_exponent(e2 as u32)
        };
        let p10bits = pow10_bits_for_index(idx);
        let len = length_for_index(idx) as i32;
        let mut i = len - 1;
        while i >= 0 {
            let j = p10bits.wrapping_sub(e2 as u32);
            digits = mul_shift_mod1e9(
                m2 << 8,
                &POW10_SPLIT[POW10_OFFSET[idx as usize] as usize + i as usize],
                j as i32 + 8,
            );
            if printed_digits != 0 {
                if printed_digits + 9 > precision {
                    available_digits = 9;
                    break;
                }
                if last - first < 9 {
                    return TOO_LARGE;
                }
                append_nine_digits(digits, buf, first);
                first += 9;
                printed_digits += 9;
            } else if digits != 0 {
                available_digits = decimal_length9(digits);
                exp = i * 9 + available_digits as i32 - 1;
                if available_digits > precision {
                    break;
                }
                if print_decimal_point {
                    if last - first < available_digits as usize + 1 {
                        return TOO_LARGE;
                    }
                    append_d_digits(available_digits, digits, buf, first);
                    first += available_digits as usize + 1; // +1 for decimal point
                } else {
                    if first == last {
                        return TOO_LARGE;
                    }
                    buf[first] = b'0' + digits as u8;
                    first += 1;
                }
                printed_digits = available_digits;
                available_digits = 0;
            }
            i -= 1;
        }
    }

    if e2 < 0 && available_digits == 0 {
        let idx = (-e2 / 16) as usize;
        let mut i = i32::from(MIN_BLOCK_2[idx]);
        while i < 200 {
            let j = ADDITIONAL_BITS_2 as i32 + (-e2 - 16 * idx as i32);
            let p = u32::from(POW10_OFFSET_2[idx]) + i as u32 - u32::from(MIN_BLOCK_2[idx]);
            digits = if p >= u32::from(POW10_OFFSET_2[idx + 1]) {
                0
            } else {
                mul_shift_mod1e9(m2 << 8, &POW10_SPLIT_2[p as usize], j + 8)
            };
            if printed_digits != 0 {
                if printed_digits + 9 > precision {
                    available_digits = 9;
                    break;
                }
                if last - first < 9 {
                    return TOO_LARGE;
                }
                append_nine_digits(digits, buf, first);
                first += 9;
                printed_digits += 9;
            } else if digits != 0 {
                available_digits = decimal_length9(digits);
                exp = -(i + 1) * 9 + available_digits as i32 - 1;
                if available_digits > precision {
                    break;
                }
                if print_decimal_point {
                    if last - first < available_digits as usize + 1 {
                        return TOO_LARGE;
                    }
                    append_d_digits(available_digits, digits, buf, first);
                    first += available_digits as usize + 1; // +1 for decimal point
                } else {
                    if first == last {
                        return TOO_LARGE;
                    }
                    buf[first] = b'0' + digits as u8;
                    first += 1;
                }
                printed_digits = available_digits;
                available_digits = 0;
            }
            i += 1;
        }
    }

    let maximum = precision - printed_digits;
    if available_digits == 0 {
        digits = 0;
    }
    let mut last_digit = 0;
    if available_digits > maximum {
        for _ in 0..available_digits - maximum {
            last_digit = digits % 10;
            digits /= 10;
        }
    }
    // 0 = don't round up; 1 = round up unconditionally; 2 = round up if odd.
    let mut round_up = if last_digit != 5 {
        i32::from(last_digit > 5)
    } else {
        // Is m * 2^e2 * 10^(precision + 1 - exp) integer?
        // precision was already increased by 1, so we don't need to write + 1 here.
        let rexp = precision as i32 - exp;
        let required_twos = -e2 - rexp;
        let mut trailing_zeros = required_twos <= 0
            || (required_twos < 60 && multiple_of_power_of2_64(m2, required_twos as u32));
        if rexp < 0 {
            let required_fives = -rexp;
            trailing_zeros = trailing_zeros && multiple_of_power_of5_64(m2, required_fives as u32);
        }
        if trailing_zeros { 2 } else { 1 }
    };
    if printed_digits != 0 {
        if last - first < maximum as usize {
            return TOO_LARGE;
        }
        if digits == 0 {
            buf[first..first + maximum as usize].fill(b'0');
        } else {
            append_c_digits(maximum, digits, buf, first);
        }
        first += maximum as usize;
    } else if print_decimal_point {
        if last - first < maximum as usize + 1 {
            return TOO_LARGE;
        }
        append_d_digits(maximum, digits, buf, first);
        first += maximum as usize + 1; // +1 for decimal point
    } else {
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'0' + digits as u8;
        first += 1;
    }
    if round_up != 0 {
        let mut round = first;
        loop {
            if round == original_first {
                buf[round] = b'1';
                exp += 1;
                break;
            }
            round -= 1;
            let c = buf[round];
            // A '.' is passed over.
            if c == b'9' {
                buf[round] = b'0';
                round_up = 1;
            } else if c != b'.' {
                if round_up == 1 || !c.is_multiple_of(2) {
                    buf[round] = c + 1;
                }
                break;
            }
        }
    }

    let sign_character = if exp < 0 {
        exp = -exp;
        b'-'
    } else {
        b'+'
    };

    let exponent_part_length = if exp >= 100 { 5 } else { 4 };
    if last - first < exponent_part_length {
        return TOO_LARGE;
    }

    buf[first] = b'e';
    buf[first + 1] = sign_character;
    first += 2;

    if exp >= 100 {
        let c = exp % 10;
        copy2(buf, first, 2 * (exp / 10) as u32);
        buf[first + 2] = b'0' + c as u8;
        first += 3;
    } else {
        copy2(buf, first, 2 * exp as u32);
        first += 2;
    }

    Ok(first)
}

