/// `__to_chars` for `__floating_decimal_64`: prints the Ryu result in the chosen notation.
fn to_chars_fd64(buf: &mut [u8], first: usize, v: FloatingDecimal64, mut fmt: Fmt, f: f64) -> Res {
    let last = buf.len();
    // Step 5: Print the decimal representation.
    let mut output = v.mantissa;
    let ryu_exponent = v.exponent;
    let olength = decimal_length17(output);
    let mut scientific_exponent = ryu_exponent + olength as i32 - 1;

    if fmt == Fmt::Plain {
        let (lower, upper) = if olength == 1 {
            (-3, 4)
        } else {
            (-(olength as i32 + 3), 5)
        };
        fmt = if lower <= ryu_exponent && ryu_exponent <= upper {
            Fmt::Fixed
        } else {
            Fmt::Scientific
        };
    } else if fmt == Fmt::General {
        fmt = if (-4..6).contains(&scientific_exponent) {
            Fmt::Fixed
        } else {
            Fmt::Scientific
        };
    }

    if fmt == Fmt::Fixed {
        let whole_digits = olength as i32 + ryu_exponent;

        let total_fixed_length: u32 = if ryu_exponent >= 0 {
            // cases "172900" and "1729"
            let mut length = whole_digits as u32;
            if output == 1 {
                length -= u32::from(ADJUSTMENT_64[ryu_exponent as usize]);
            }
            length
        } else if whole_digits > 0 {
            // case "17.29"
            olength + 1
        } else {
            // case "0.001729"
            (2 - ryu_exponent) as u32
        };

        if last - first < total_fixed_length as usize {
            return TOO_LARGE;
        }

        let mut mid = if ryu_exponent > 0 {
            // case "172900"
            let can_use_ryu = if ryu_exponent > 22 {
                // 10^22 is the largest power of 10 that's exactly representable as a double.
                false
            } else {
                let trailing_zero_bits = v.mantissa.trailing_zeros();
                let shifted_mantissa = v.mantissa >> trailing_zero_bits;
                shifted_mantissa <= MAX_SHIFTED_MANTISSA_64[ryu_exponent as usize]
            };

            if !can_use_ryu {
                // Print the integer exactly.
                return d2fixed_buffered_n(buf, first, f, 0);
            }

            // Print the decimal digits, left-aligned within [first, first + total_fixed_length).
            first + olength as usize
        } else {
            // cases "1729", "17.29", and "0.001729"
            // Print the decimal digits, right-aligned within [first, first + total_fixed_length).
            first + total_fixed_length as usize
        };

        // We prefer 32-bit operations: if output doesn't fit into u32, cut off 8 digits.
        if (output >> 32) != 0 {
            // Expensive 64-bit division.
            let q = div1e8(output);
            let mut output2 = (output - 100_000_000 * q) as u32;
            output = q;

            let c = output2 % 10000;
            output2 /= 10000;
            let d = output2 % 10000;
            let c0 = (c % 100) << 1;
            let c1 = (c / 100) << 1;
            let d0 = (d % 100) << 1;
            let d1 = (d / 100) << 1;

            mid -= 2;
            copy2(buf, mid, c0);
            mid -= 2;
            copy2(buf, mid, c1);
            mid -= 2;
            copy2(buf, mid, d0);
            mid -= 2;
            copy2(buf, mid, d1);
        }
        write_digits_backwards32(buf, mid, output as u32);
        finish_fixed(buf, first, olength, ryu_exponent, whole_digits);

        return Ok(first + total_fixed_length as usize);
    }

    let total_scientific_length = olength
        + u32::from(olength > 1)
        + if -100 < scientific_exponent && scientific_exponent < 100 {
            4
        } else {
            5
        };
    if last - first < total_scientific_length as usize {
        return TOO_LARGE;
    }
    let result = first;
    let olength_u = olength as usize;

    // Print the decimal digits.
    let mut i = 0usize;
    if (output >> 32) != 0 {
        // Expensive 64-bit division.
        let q = div1e8(output);
        let mut output2 = (output as u32).wrapping_sub(100_000_000u32.wrapping_mul(q as u32));
        output = q;

        let c = output2 % 10000;
        output2 /= 10000;
        let d = output2 % 10000;
        let c0 = (c % 100) << 1;
        let c1 = (c / 100) << 1;
        let d0 = (d % 100) << 1;
        let d1 = (d / 100) << 1;
        copy2(buf, result + olength_u - i - 1, c0);
        copy2(buf, result + olength_u - i - 3, c1);
        copy2(buf, result + olength_u - i - 5, d0);
        copy2(buf, result + olength_u - i - 7, d1);
        i += 8;
    }
    let mut output2 = output as u32;
    while output2 >= 10000 {
        let c = output2 % 10000;
        output2 /= 10000;
        let c0 = (c % 100) << 1;
        let c1 = (c / 100) << 1;
        copy2(buf, result + olength_u - i - 1, c0);
        copy2(buf, result + olength_u - i - 3, c1);
        i += 4;
    }
    if output2 >= 100 {
        let c = (output2 % 100) << 1;
        output2 /= 100;
        copy2(buf, result + olength_u - i - 1, c);
    }
    if output2 >= 10 {
        let c = (output2 << 1) as usize;
        // The decimal dot goes between these two digits.
        buf[result + 2] = DIGIT_TABLE[c + 1];
        buf[result] = DIGIT_TABLE[c];
    } else {
        buf[result] = b'0' + output2 as u8;
    }

    // Print decimal point if needed.
    let mut index = if olength > 1 {
        buf[result + 1] = b'.';
        olength_u + 1
    } else {
        1
    };

    // Print the exponent.
    buf[result + index] = b'e';
    index += 1;
    if scientific_exponent < 0 {
        buf[result + index] = b'-';
        scientific_exponent = -scientific_exponent;
    } else {
        buf[result + index] = b'+';
    }
    index += 1;

    if scientific_exponent >= 100 {
        let c = scientific_exponent % 10;
        copy2(buf, result + index, 2 * (scientific_exponent / 10) as u32);
        buf[result + index + 2] = b'0' + c as u8;
    } else {
        copy2(buf, result + index, 2 * scientific_exponent as u32);
    }

    Ok(first + total_scientific_length as usize)
}

/// `__d2d_small_int`: an integer in [1, 2^53) as `mantissa * 10^0`, or `None`.
fn d2d_small_int(ieee_mantissa: u64, ieee_exponent: u32) -> Option<FloatingDecimal64> {
    let m2 = (1u64 << DOUBLE_MANTISSA_BITS) | ieee_mantissa;
    let e2 = ieee_exponent as i32 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS;

    if e2 > 0 {
        // f = m2 * 2^e2 >= 2^53 is an integer. Ignore this case for now.
        return None;
    }
    if e2 < -52 {
        // f < 1.
        return None;
    }

    // Since 2^52 <= m2 < 2^53 and 0 <= -e2 <= 52: 1 <= f = m2 / 2^-e2 < 2^53.
    // Test if the lower -e2 bits of the significand are 0, i.e. whether the fraction is 0.
    let mask = (1u64 << -e2) - 1;
    let fraction = m2 & mask;
    if fraction != 0 {
        return None;
    }

    // f is an integer in the range [1, 2^53).
    Some(FloatingDecimal64 {
        mantissa: m2 >> -e2,
        exponent: 0,
    })
}

/// `__d2s_buffered_n`: the shortest form of a `double` (not negative, finite).
fn d2s_buffered_n(buf: &mut [u8], first: usize, f: f64, fmt: Fmt) -> Res {
    let last = buf.len();
    // Step 1: Decode the floating-point number, and unify normalized and subnormal cases.
    let bits = f.to_bits();

    // Case distinction; exit early for the easy cases.
    if bits == 0 {
        if fmt == Fmt::Scientific {
            if last - first < 5 {
                return TOO_LARGE;
            }
            buf[first..first + 5].copy_from_slice(b"0e+00");
            return Ok(first + 5);
        }
        // Print "0" for chars_format::fixed, chars_format::general, and chars_format{}.
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'0';
        return Ok(first + 1);
    }

    // Decode bits into mantissa and exponent.
    let ieee_mantissa = bits & ((1u64 << DOUBLE_MANTISSA_BITS) - 1);
    let ieee_exponent = (bits >> DOUBLE_MANTISSA_BITS) as u32;

    if fmt == Fmt::Fixed {
        let exponent2 = ieee_exponent as i32 - DOUBLE_BIAS - DOUBLE_MANTISSA_BITS;
        // Positive exponents are the non-dense range of exactly representable integers:
        // print them exactly, skipping Ryu.
        if exponent2 > 0 {
            return d2fixed_buffered_n(buf, first, f, 0);
        }
    }

    let v = match d2d_small_int(ieee_mantissa, ieee_exponent) {
        Some(mut v) => {
            // For small integers in the range [1, 2^53), v.mantissa might contain trailing
            // (decimal) zeros. For scientific notation we need to move these zeros into the
            // exponent.
            loop {
                let q = div10(v.mantissa);
                let r = (v.mantissa as u32).wrapping_sub(10u32.wrapping_mul(q as u32));
                if r != 0 {
                    break;
                }
                v.mantissa = q;
                v.exponent += 1;
            }
            v
        }
        None => d2d(ieee_mantissa, ieee_exponent),
    };

    to_chars_fd64(buf, first, v, fmt, f)
}

