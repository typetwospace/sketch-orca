/// `_Floating_to_chars_hex_precision`: `%.*a`'s digits without the `0x`, for a value that is not
/// negative; a negative precision is the full precision.
fn hex_precision<T: Floating>(
    buf: &mut [u8],
    mut first: usize,
    value: T,
    mut precision: i32,
) -> Res {
    let last = buf.len();
    let full_precision = T::FULL_PRECISION;
    let adjusted_explicit_bits = full_precision * 4;

    if precision < 0 {
        precision = full_precision;
    }

    // Extract the ieee_mantissa and ieee_exponent.
    let uint_value = value.bits();
    let ieee_mantissa = uint_value & T::MANTISSA_MASK;
    let ieee_exponent = (uint_value >> T::MANTISSA_BITS) as i32;

    // Prepare the adjusted_mantissa, aligned to hexit boundaries, with the implicit bit restored.
    let mut adjusted_mantissa = if T::IS_DOUBLE {
        ieee_mantissa // already aligned (52 is divisible by 4)
    } else {
        ieee_mantissa << 1 // align to hexit boundary (23 isn't divisible by 4)
    };

    let unbiased_exponent = if ieee_exponent == 0 {
        // zero or subnormal: implicit bit is 0
        if ieee_mantissa == 0 {
            // "If the value is zero, the exponent is zero."
            0
        } else {
            1 - T::EXPONENT_BIAS
        }
    } else {
        // normal: implicit bit is 1
        adjusted_mantissa |= 1u64 << adjusted_explicit_bits;
        ieee_exponent - T::EXPONENT_BIAS
    };

    // Decompose unbiased_exponent into sign_character and absolute_exponent.
    let (sign_character, absolute_exponent) = if unbiased_exponent < 0 {
        (b'-', (-unbiased_exponent) as u32)
    } else {
        (b'+', unbiased_exponent as u32)
    };

    // Perform a single bounds check.
    {
        let exponent_length = if absolute_exponent < 10 {
            1
        } else if absolute_exponent < 100 {
            2
        } else if absolute_exponent < 1000 {
            3
        } else {
            4
        };

        // precision might be enormous; avoid integer overflow by testing it separately.
        let mut buffer_size = (last - first) as i64;
        if buffer_size < i64::from(precision) {
            return TOO_LARGE;
        }
        buffer_size -= i64::from(precision);

        let length_excluding_precision = 1 + i64::from(precision > 0) + 2 + exponent_length;
        if buffer_size < length_excluding_precision {
            return TOO_LARGE;
        }
    }

    // Perform rounding when we've been asked to omit hexits.
    if precision < full_precision {
        let dropped_bits = (full_precision - precision) * 4;
        let lsb_bit = adjusted_mantissa;
        let round_bit = adjusted_mantissa << 1;
        let has_tail_bits = round_bit.wrapping_sub(1);
        let should_round = round_bit & (has_tail_bits | lsb_bit) & (1u64 << dropped_bits);
        // This rounding technique is dedicated to the memory of Peppermint. =^..^=
        adjusted_mantissa += should_round;
    }

    // Print the leading hexit, then mask it away.
    {
        let nibble = (adjusted_mantissa >> adjusted_explicit_bits) as u32;
        debug_assert!(nibble < 3);
        buf[first] = b'0' + nibble as u8;
        first += 1;
        let mask = (1u64 << adjusted_explicit_bits) - 1;
        adjusted_mantissa &= mask;
    }

    // Print the decimal point and trailing hexits.
    if precision > 0 {
        buf[first] = b'.';
        first += 1;

        let mut number_of_bits_remaining = adjusted_explicit_bits;
        loop {
            number_of_bits_remaining -= 4;
            let nibble = (adjusted_mantissa >> number_of_bits_remaining) as u32;
            debug_assert!(nibble < 16);
            buf[first] = CHARCONV_DIGITS[nibble as usize];
            first += 1;

            // precision is the number of hexits that still need to be printed.
            precision -= 1;
            if precision == 0 {
                break;
            }

            if number_of_bits_remaining == 0 {
                // All remaining hexits are '0'.
                buf[first..first + precision as usize].fill(b'0');
                first += precision as usize;
                break;
            }

            let mask = (1u64 << number_of_bits_remaining) - 1;
            adjusted_mantissa &= mask;
        }
    }

    // Print the exponent.
    buf[first] = b'p';
    buf[first + 1] = sign_character;
    first += 2;

    integer_digits(buf, first, u64::from(absolute_exponent), 10)
}

/// `_Floating_to_chars_hex_shortest`: the shortest hexadecimal form without the `0x`, for a value
/// that is not negative.
fn hex_shortest<T: Floating>(buf: &mut [u8], mut first: usize, value: T) -> Res {
    let last = buf.len();
    let uint_value = value.bits();

    if uint_value == 0 {
        // "If the value is zero, the exponent is zero."
        if last - first < 4 {
            return TOO_LARGE;
        }
        buf[first..first + 4].copy_from_slice(b"0p+0");
        return Ok(first + 4);
    }

    let ieee_mantissa = uint_value & T::MANTISSA_MASK;
    let ieee_exponent = (uint_value >> T::MANTISSA_BITS) as i32;

    let (leading_hexit, mut unbiased_exponent) = if ieee_exponent == 0 {
        (b'0', 1 - T::EXPONENT_BIAS) // subnormal
    } else {
        (b'1', ieee_exponent - T::EXPONENT_BIAS) // normal
    };

    if first == last {
        return TOO_LARGE;
    }
    buf[first] = leading_hexit;
    first += 1;

    if ieee_mantissa != 0 {
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'.';
        first += 1;

        let (mut adjusted_mantissa, mut number_of_bits_remaining) = if T::IS_DOUBLE {
            (ieee_mantissa, 52)
        } else {
            (ieee_mantissa << 1, 24)
        };

        // Print a hexit, mask it away, and keep looping while fraction bits remain.
        loop {
            number_of_bits_remaining -= 4;
            let nibble = (adjusted_mantissa >> number_of_bits_remaining) as u32;
            debug_assert!(nibble < 16);
            if first == last {
                return TOO_LARGE;
            }
            buf[first] = CHARCONV_DIGITS[nibble as usize];
            first += 1;
            let mask = (1u64 << number_of_bits_remaining) - 1;
            adjusted_mantissa &= mask;
            if adjusted_mantissa == 0 {
                break;
            }
        }
    }

    if last - first < 2 {
        return TOO_LARGE;
    }
    buf[first] = b'p';
    first += 1;
    if unbiased_exponent < 0 {
        buf[first] = b'-';
        unbiased_exponent = -unbiased_exponent;
    } else {
        buf[first] = b'+';
    }
    first += 1;

    integer_digits(buf, first, unbiased_exponent as u64, 10)
}

/// `_Floating_to_chars_general_precision`: `%.*g`'s characters, for a value that is not negative.
fn general_precision<T: Floating>(
    buf: &mut [u8],
    mut first: usize,
    value: T,
    mut precision: i32,
) -> Res {
    let last = buf.len();
    let uint_value = value.bits();

    if uint_value == 0 {
        // zero detected; write "0" and return; precision is irrelevant due to zero-trimming
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'0';
        return Ok(first + 1);
    }

    // "Let P equal the precision if nonzero, 6 if the precision is omitted, or 1 if the precision
    // is zero."
    if precision < 0 {
        precision = 6;
    } else if precision == 0 {
        precision = 1;
    } else if precision >= 1_000_000 {
        // Due to general notation's zero-trimming behavior, we can simply clamp precision.
        precision = 1_000_000;
    }

    // precision is now the Standard's P.
    let (table_begin, table_len, special) = if precision <= T::MAX_SPECIAL_P {
        (
            ((precision - 1) * (precision + 10) / 2) as usize,
            (precision + 5) as usize,
            true,
        )
    } else {
        (0, (precision.min(T::MAX_P) + 5) as usize, false)
    };
    let elem = |k: usize| {
        if special {
            T::special_x(table_begin + k)
        } else {
            T::ordinary_x(table_begin + k)
        }
    };

    // The index of the first element not below the value: lower_bound for double above
    // P = 155, find_if otherwise (the same element, the tables being sorted).
    let table_index = if T::IS_DOUBLE && precision > 155 {
        let (mut lo, mut count) = (0usize, table_len);
        while count > 0 {
            let step = count / 2;
            if elem(lo + step) < uint_value {
                lo += step + 1;
                count -= step + 1;
            } else {
                count = step;
            }
        }
        lo
    } else {
        let mut k = 0;
        while k < table_len && uint_value > elem(k) {
            k += 1;
        }
        k
    };

    let scientific_exponent_x = table_index as i32 - 5;
    let use_fixed_notation = precision > scientific_exponent_x && scientific_exponent_x >= -4;

    // Write into a local buffer, zero-trim, then copy into the output range.
    let mut buffer = [0u8; 773];
    let buffer = &mut buffer[..T::MAX_OUTPUT_LENGTH];
    let significand_first = 0usize;
    let mut significand_last;
    let mut exponent_range = 0..0;
    let effective_precision;

    if use_fixed_notation {
        let p = precision - (scientific_exponent_x + 1);
        effective_precision = p.min(T::MAX_FIXED_PRECISION);
        let end = fixed_precision(buffer, 0, value, effective_precision);
        debug_assert!(end.is_ok());
        significand_last = end.unwrap_or(0);
    } else {
        let p = precision - 1;
        effective_precision = p.min(T::MAX_SCIENTIFIC_PRECISION);
        let end = scientific_precision(buffer, 0, value, effective_precision);
        debug_assert!(end.is_ok());
        let end = end.unwrap_or(0);
        significand_last = buffer[..end].iter().position(|&c| c == b'e').unwrap_or(end);
        exponent_range = significand_last..end;
    }

    // If we printed a decimal point followed by digits, perform zero-trimming.
    if effective_precision > 0 {
        while buffer[significand_last - 1] == b'0' {
            // will stop at '.' or a nonzero digit
            significand_last -= 1;
        }
        if buffer[significand_last - 1] == b'.' {
            significand_last -= 1;
        }
    }

    // Copy the significand to the output range.
    let significand_distance = significand_last - significand_first;
    if last - first < significand_distance {
        return TOO_LARGE;
    }
    buf[first..first + significand_distance]
        .copy_from_slice(&buffer[significand_first..significand_last]);
    first += significand_distance;

    // Copy the exponent to the output range.
    if !use_fixed_notation {
        let exponent_distance = exponent_range.len();
        if last - first < exponent_distance {
            return TOO_LARGE;
        }
        buf[first..first + exponent_distance].copy_from_slice(&buffer[exponent_range]);
        first += exponent_distance;
    }

    Ok(first)
}

/// `_Floating_to_chars_overload`: which `to_chars` overload was called.
#[derive(Clone, Copy)]
enum Overload {
    Plain,
    FormatOnly(CharsFormat),
    FormatPrecision(CharsFormat, i32),
}

/// `_Floating_to_chars`: the sign, then inf and the NaNs, then the overload's notation.
fn floating_to_chars<T: Floating>(buf: &mut [u8], value: T, overload: Overload) -> Res {
    let last = buf.len();
    let mut first = 0;
    let mut uint_value = value.bits();
    let mut value = value;

    let was_negative = (uint_value & T::SIGN_MASK) != 0;
    if was_negative {
        // sign bit detected; write minus sign and clear sign bit
        if first == last {
            return TOO_LARGE;
        }
        buf[first] = b'-';
        first += 1;
        uint_value &= !T::SIGN_MASK;
        value = T::from_bits_u64(uint_value);
    }

    if (uint_value & T::EXPONENT_MASK) == T::EXPONENT_MASK {
        // inf/nan detected; write appropriate string and return
        let mantissa = uint_value & T::MANTISSA_MASK;
        let s: &[u8] = if mantissa == 0 {
            b"inf"
        } else if was_negative && mantissa == T::QUIET_BIT {
            // The UCRT's "indeterminate": sign bit and quiet bit set, other mantissa bits clear.
            b"nan(ind)"
        } else if (mantissa & T::QUIET_BIT) != 0 {
            b"nan"
        } else {
            b"nan(snan)"
        };
        if last - first < s.len() {
            return TOO_LARGE;
        }
        buf[first..first + s.len()].copy_from_slice(s);
        return Ok(first + s.len());
    }

    match overload {
        Overload::Plain => T::ryu(buf, first, value, CharsFormatInternal(Fmt::Plain)),
        Overload::FormatOnly(fmt) => match fmt {
            CharsFormat::Hex => hex_shortest(buf, first, value),
            CharsFormat::Scientific => {
                T::ryu(buf, first, value, CharsFormatInternal(Fmt::Scientific))
            }
            CharsFormat::Fixed => T::ryu(buf, first, value, CharsFormatInternal(Fmt::Fixed)),
            CharsFormat::General => T::ryu(buf, first, value, CharsFormatInternal(Fmt::General)),
        },
        Overload::FormatPrecision(fmt, precision) => match fmt {
            CharsFormat::Scientific => scientific_precision(buf, first, value, precision),
            CharsFormat::Fixed => fixed_precision(buf, first, value, precision),
            CharsFormat::General => general_precision(buf, first, value, precision),
            CharsFormat::Hex => hex_precision(buf, first, value, precision),
        },
    }
}

/// `std::to_chars(first, last, value)`: the shortest characters that read back as `value`, in
/// fixed notation or scientific notation, whichever is shorter (fixed on a tie). Returns the
/// number of bytes written at the start of `buf`.
///
/// # Errors
///
/// [`Errc::ValueTooLarge`] when `buf` is too short.
pub fn to_chars<T: Floating>(buf: &mut [u8], value: T) -> Result<usize, Errc> {
    floating_to_chars(buf, value, Overload::Plain)
}

/// `std::to_chars(first, last, value, fmt)`: the shortest round-trip characters in the given
/// notation (`General` picks fixed for exponents from -4 to 5); `Hex` gives the shortest exact
/// hexadecimal form, `1.8p+0` (no `0x`).
///
/// # Errors
///
/// [`Errc::ValueTooLarge`] when `buf` is too short.
pub fn to_chars_format<T: Floating>(
    buf: &mut [u8],
    value: T,
    fmt: CharsFormat,
) -> Result<usize, Errc> {
    floating_to_chars(buf, value, Overload::FormatOnly(fmt))
}

/// `std::to_chars(first, last, value, fmt, precision)`: printf's `%.*e`, `%.*f`, `%.*g` and
/// `%.*a` (without `0x`) for `Scientific`, `Fixed`, `General` and `Hex`. A negative precision is
/// the default (6, or the full precision for `Hex`). `General` trims trailing zeros, as `%g` does
/// without `#`.
///
/// # Errors
///
/// [`Errc::ValueTooLarge`] when `buf` is too short, and for a precision of 10^9 or more in
/// `Scientific` and `Fixed`.
pub fn to_chars_precision<T: Floating>(
    buf: &mut [u8],
    value: T,
    fmt: CharsFormat,
    precision: i32,
) -> Result<usize, Errc> {
    floating_to_chars(buf, value, Overload::FormatPrecision(fmt, precision))
}

/// The bytes a buffer needs for any result of [`to_chars_precision`] with this precision (at
/// least those of the shortest forms).
fn capacity_for(precision: i32) -> usize {
    // Sign, 309 integer digits, point, the precision's digits and an exponent: 330 covers all
    // but the digits; the general form's own buffer is 773.
    let p = if precision > 0 { precision as usize } else { 0 };
    p + 800
}

/// The characters as a `String`: the bytes are ASCII.
fn ascii_string(mut buf: Vec<u8>, len: usize) -> String {
    buf.truncate(len);
    buf.into_iter().map(char::from).collect()
}

/// [`to_chars`] into a `String`.
#[must_use]
pub fn to_chars_string<T: Floating>(value: T) -> String {
    let mut buf = vec![0u8; capacity_for(0)];
    let len = to_chars(&mut buf, value).unwrap_or(0);
    ascii_string(buf, len)
}

/// [`to_chars_format`] into a `String`.
#[must_use]
pub fn to_chars_format_string<T: Floating>(value: T, fmt: CharsFormat) -> String {
    let mut buf = vec![0u8; capacity_for(0)];
    let len = to_chars_format(&mut buf, value, fmt).unwrap_or(0);
    ascii_string(buf, len)
}

/// [`to_chars_precision`] into a `String`.
///
/// # Errors
///
/// [`Errc::ValueTooLarge`] for a precision of 10^9 or more in `Scientific`, `Fixed` and `Hex`
/// (C++ would need a buffer of that size for `Hex`; this function does not allocate one).
pub fn to_chars_precision_string<T: Floating>(
    value: T,
    fmt: CharsFormat,
    precision: i32,
) -> Result<String, Errc> {
    if precision >= 1_000_000_000 && fmt != CharsFormat::General {
        return Err(Errc::ValueTooLarge);
    }
    // General trims its zeros: its result fits its own 773-byte buffer.
    let mut buf = vec![
        0u8;
        if fmt == CharsFormat::General {
            capacity_for(0)
        } else {
            capacity_for(precision)
        }
    ];
    let len = to_chars_precision(&mut buf, value, fmt, precision)?;
    Ok(ascii_string(buf, len))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn s<T: Floating>(v: T) -> String {
        to_chars_string(v)
    }

    fn p(v: f64, fmt: CharsFormat, precision: i32) -> String {
        to_chars_precision_string(v, fmt, precision).unwrap_or_default()
    }

    #[test]
    fn shortest_forms() {
        assert_eq!(s(0.1f64), "0.1");
        assert_eq!(s(1.0f64), "1");
        assert_eq!(s(-0.0f64), "-0");
        assert_eq!(s(1e23f64), "1e+23");
        assert_eq!(s(123456.0f64), "123456");
        assert_eq!(s(1e21f64), "1e+21");
        assert_eq!(s(5e-324f64), "5e-324");
        assert_eq!(s(f64::MAX), "1.7976931348623157e+308");
        assert_eq!(s(0.3f32), "0.3");
        assert_eq!(s(1e11f32), "1e+11");
        assert_eq!(s(f64::INFINITY), "inf");
        assert_eq!(s(f64::from_bits(0xFFF8_0000_0000_0000)), "-nan(ind)");
        assert_eq!(s(f64::from_bits(0x7FF0_0000_0000_0001)), "nan(snan)");
        assert_eq!(s(f64::from_bits(0xFFF8_0000_0000_0001)), "-nan");
    }

    #[test]
    fn format_forms() {
        // Fixed prints the exact integer value of large doubles and floats.
        assert_eq!(
            to_chars_format_string(1e23f64, CharsFormat::Fixed),
            "99999999999999991611392"
        );
        assert_eq!(
            to_chars_format_string(9.5e22f64, CharsFormat::Fixed),
            "94999999999999993708544"
        );
        assert_eq!(
            to_chars_format_string(1e11f32, CharsFormat::Fixed),
            "99999997952"
        );
        assert_eq!(
            to_chars_format_string(1e22f64, CharsFormat::Fixed),
            "10000000000000000000000"
        );
        assert_eq!(to_chars_format_string(123.0f64, CharsFormat::Fixed), "123");
        assert_eq!(to_chars_format_string(1.5f64, CharsFormat::Hex), "1.8p+0");
        assert_eq!(to_chars_format_string(0.0f64, CharsFormat::Hex), "0p+0");
        assert_eq!(
            to_chars_format_string(5e-324f64, CharsFormat::Hex),
            "0.0000000000001p-1022"
        );
        assert_eq!(
            to_chars_format_string(1234.5f64, CharsFormat::Scientific),
            "1.2345e+03"
        );
        assert_eq!(
            to_chars_format_string(1e-5f64, CharsFormat::General),
            "1e-05"
        );
    }

    #[test]
    fn precision_forms() {
        assert_eq!(p(0.1, CharsFormat::Fixed, 20), "0.10000000000000000555");
        assert_eq!(p(2.5, CharsFormat::Fixed, 0), "2");
        assert_eq!(p(9.5, CharsFormat::Scientific, 0), "1e+01");
        assert_eq!(p(9.995, CharsFormat::Fixed, 2), "9.99");
        assert_eq!(p(99.99, CharsFormat::Fixed, 1), "100.0");
        assert_eq!(p(1e300, CharsFormat::Scientific, 3), "1.000e+300");
        assert_eq!(p(1.0, CharsFormat::Hex, -1), "1.0000000000000p+0");
        assert_eq!(p(1.0, CharsFormat::Hex, 0), "1p+0");
        assert_eq!(p(1.96875, CharsFormat::Hex, 0), "2p+0");
        assert_eq!(p(100000.0, CharsFormat::General, -1), "100000");
        assert_eq!(p(1000000.0, CharsFormat::General, -1), "1e+06");
        assert_eq!(p(0.0001234567, CharsFormat::General, -1), "0.000123457");
        assert_eq!(p(9.5, CharsFormat::General, 1), "1e+01");
        assert_eq!(
            to_chars_precision_string(1.0, CharsFormat::Fixed, 1_000_000_000),
            Err(Errc::ValueTooLarge)
        );
    }

    #[test]
    fn integers() {
        let mut buf = [0u8; 70];
        let n = to_chars_i64(&mut buf, i64::MIN, 10).unwrap_or(0);
        assert_eq!(&buf[..n], b"-9223372036854775808");
        let n = to_chars_u64(&mut buf, u64::MAX, 2).unwrap_or(0);
        assert_eq!(n, 64);
        let n = to_chars_u64(&mut buf, 35, 36).unwrap_or(0);
        assert_eq!(&buf[..n], b"z");
        assert_eq!(
            to_chars_i64(&mut buf[..3], -100, 10),
            Err(Errc::ValueTooLarge)
        );
    }

    #[test]
    fn too_small_buffers_fail_without_panicking() {
        let values = [
            0.0,
            1.0,
            0.1,
            1e23,
            5e-324,
            123.456,
            f64::MAX,
            f64::NAN,
            -1.5,
        ];
        for v in values {
            for len in 0..12 {
                let mut buf = vec![0u8; len];
                let _ = to_chars(&mut buf, v);
                for fmt in [
                    CharsFormat::Scientific,
                    CharsFormat::Fixed,
                    CharsFormat::Hex,
                    CharsFormat::General,
                ] {
                    let _ = to_chars_format(&mut buf, v, fmt);
                    for precision in [-1, 0, 3, 17, 30] {
                        let _ = to_chars_precision(&mut buf, v, fmt, precision);
                    }
                }
            }
        }
    }
}
