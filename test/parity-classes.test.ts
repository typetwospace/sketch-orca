// The classes of an output (scripts/lib/parity/classes.ts) and what is built on them: the thread
// counts parity record runs at, the outputs of a run, parity.json's families, the H-sites of
// parity goldens --check (goldens.ts), paths made portable, and the self-variance envelope
// (envelope.ts). Hermetic: in-memory outputs and temporary stores.

import { afterEach, beforeEach, describe, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { classesOf, classify, portableBytes, portableText } from '../scripts/lib/parity/classes.ts'
import type { CorpusDocument } from '../scripts/lib/parity/corpus.ts'
import { lineShape, outputEnvelope } from '../scripts/lib/parity/envelope.ts'
import { folderDifferences, withHSites } from '../scripts/lib/parity/goldens.ts'
import { readMasks } from '../scripts/lib/parity/masks.ts'
import { outputNames, parityDocument, PARITY_FORMAT, portableRoots, recordThreads, type OutputRecord } from '../scripts/lib/parity/record.ts'

const B = (s: string) => Buffer.from(s)

let tmp: string
beforeEach(() => {
  tmp = mkdtempSync(join(tmpdir(), 'parity-classes-'))
})
afterEach(() => {
  rmSync(tmp, { recursive: true, force: true })
})

describe('classify', () => {
  test('B: the same bytes everywhere', () => {
    const c = classify({ name: 'out.gcode', oracle: [B('G1 X1\n'), B('G1 X1\n')], engine: [B('G1 X1\n'), B('G1 X1\n')] }, [])
    expect(c.class).toBe('B')
    expect(c.flags).toEqual(['B'])
  })

  test('T: the oracle differs between thread counts', () => {
    const c = classify({ name: 'out.gcode', oracle: [B('G1 X1\n'), B('G1 X2\n')], engine: [B('G1 X1\n'), B('G1 X1\n')] }, [])
    expect(c.class).toBe('T')
  })

  test('R: the engine differs between its own runs where no mask applies, and wins over T', () => {
    const c = classify({ name: 'out.gcode', oracle: [B('G1 X1\n'), B('G1 X2\n')], engine: [B('G1 X1\n'), B('G1 X3\n')] }, [])
    expect(c.class).toBe('R')
    expect(c.flags).toEqual(['R', 'T'])
  })

  test('N: the oracle differs from a steady engine where no mask applies', () => {
    const c = classify({ name: 'result.json', oracle: [B('{"a":1}'), B('{"a":1}')], engine: [B('{"a":2}'), B('{"a":2}')] }, [])
    expect(c.class).toBe('N')
  })

  test("E: only masked fields differ (the G-code header's time, masks.json)", () => {
    const { masks } = readMasks()
    const at = (t: string) => B(`; generated by sketch-orca on 2026-01-01 at ${t}\nG1 X1\n`)
    const c = classify({ name: 'out.gcode', oracle: [at('00:00:00'), at('00:00:00')], engine: [at('12:00:00'), at('12:00:01')] }, masks)
    expect(c.class).toBe('E')
    expect(c.details.E).toBe('gcode-generated-on')
    // The same difference outside a masked line is R.
    expect(classify({ name: 'out.gcode', oracle: [B('G1 X1\n')], engine: [B('G1 X1\n'), B('G1 X2\n')] }, masks).class).toBe('R')
  })

  test('H: the folders differ, and it is the class whatever else holds', () => {
    const c = classify({ name: 'out.gcode', oracle: [B('x')], engine: [B('x')], folderRan: true, folder: B('y'), oraclePortable: B('x') }, [])
    expect(c.class).toBe('H')
    expect(classify({ name: 'out.gcode', oracle: [B('x')], engine: [B('x')], folderRan: true, folder: undefined, oraclePortable: B('x') }, []).details.H).toMatch(/one folder only/)
  })

  test('an output one side never wrote is a difference', () => {
    expect(classify({ name: 'a.txt', oracle: [B('x'), undefined], engine: [B('x')] }, []).class).toBe('T')
    expect(classify({ name: 'a.txt', oracle: [undefined, undefined], engine: [undefined, undefined] }, []).class).toBe('B')
  })

  test('classesOf orders and dedupes', () => {
    expect(classesOf(['B', 'E', 'T', 'B', 'H'])).toEqual(['H', 'T', 'E', 'B'])
  })
})

describe('portable paths', () => {
  test('a path is replaced as written, with forward slashes and JSON-escaped; the longest first', () => {
    const roots: [string, string][] = [
      ['C:\\w\\parity\\runs\\record\\cases', '<cases>'],
      ['C:\\w\\parity\\runs\\record\\cases\\x', '<case>'],
      ['C:\\w', '<work>'],
    ]
    expect(portableText('"C:\\\\w\\\\parity\\\\runs\\\\record\\\\cases\\\\x\\\\out.gcode"', roots)).toBe('"<case>\\\\out.gcode"')
    expect(portableText('C:/w/parity/runs/record/cases/y/a and C:\\w\\z', roots)).toBe('<cases>/y/a and <work>\\z')
    expect(portableBytes(B('PK\u0003\u0004C:\\w'), roots)!.toString('latin1')).toBe('PK\u0003\u0004C:\\w')
    expect(portableBytes(B('p: C:\\w\\Büchse.3mf'), roots)!.toString('utf8')).toBe('p: <work>\\Büchse.3mf')
    expect(portableRoots({ root: 'R', caseId: 'c', resources: 'S', work: 'W' }).map((r) => r[1])).toEqual(['<case>', '<cases>', '<resources>', '<work>'])
  })
})

describe('record', () => {
  test('the thread counts: 1, 2, 8 and the machine, each once', () => {
    expect(recordThreads(32)).toEqual([1, 2, 8, 32])
    expect(recordThreads(8)).toEqual([1, 2, 8])
    expect(recordThreads(4)).toEqual([1, 2, 4, 8])
    expect(recordThreads(0)).toEqual([1, 2, 8])
  })

  test("a run's outputs: exit, stdout, stderr, the files and the removals of every pass, sorted", () => {
    const r = (files: string[], gone: string[] = []) => ({ index: 0, args: [], extraEnv: [], code: 0, timedOut: false, files, gone })
    expect(outputNames([r(['b.txt', 'a.txt']), r(['c.txt'], ['old']), undefined])).toEqual(['exit', 'stdout', 'stderr', 'files/a.txt', 'files/b.txt', 'files/c.txt', 'removed/old'])
  })

  test('parity.json: every family with its cases, their classes, and certified false unless certified before', () => {
    const doc = {
      families: [
        { name: 'version', step: 'front end', what: 'v' },
        { name: 'info', step: 'info', what: 'i' },
        { name: 'raft', step: 'posSupportMaterial', what: 'r' },
      ],
      cases: [
        { id: 'smoke-version', kind: 'smoke', title: '', families: ['version'] },
        { id: 'mesh-a-info', kind: 'job', title: '', families: ['info'] },
      ],
    } as unknown as CorpusDocument
    const outputs: OutputRecord[] = [
      { case: 'smoke-version', run: 0, output: 'stdout', class: 'B', flags: ['B'], details: {} },
      { case: 'mesh-a-info', run: 0, output: 'files/result.json', class: 'E', flags: ['E'], details: {} },
      { case: 'mesh-a-info', run: 0, output: 'exit', class: 'B', flags: ['B'], details: {} },
    ]
    const p = parityDocument({ doc, corpusSha256: 'x', threads: [1, 2, 8], engineRuns: 5, outputs, hSites: [] })
    expect(p.format).toBe(PARITY_FORMAT)
    expect(p.families.map((f) => [f.name, f.cases, f.classes, f.certified])).toEqual([
      ['version', ['smoke-version'], ['B'], false],
      ['info', ['mesh-a-info'], ['E', 'B'], false],
      ['raft', [], [], false],
    ])
    const again = parityDocument({ doc, corpusSha256: 'x', threads: [1], engineRuns: 5, outputs, hSites: [], previous: { ...p, families: p.families.map((f) => ({ ...f, certified: f.name === 'version' })) } })
    expect(again.families.map((f) => f.certified)).toEqual([true, false, false])
  })
})

describe('goldens --check', () => {
  function store(base: string, caseId: string, files: Record<string, string>, stdout = ''): void {
    const d = join(base, caseId, '0')
    mkdirSync(join(d, 'files'), { recursive: true })
    writeFileSync(join(d, 'stdout'), stdout)
    writeFileSync(join(d, 'stderr'), '')
    for (const [k, v] of Object.entries(files)) writeFileSync(join(d, 'files', k), v)
  }
  const run = (files: string[]) => ({ index: 0, args: [], extraEnv: [], code: 0, timedOut: false, files, gone: [] })

  test("outputs that differ once each folder's paths are portable are H-sites; the paths themselves are not", () => {
    const a = join(tmp, 'a')
    const b = join(tmp, 'b')
    const ra = join(tmp, 'wa', 'cases')
    const rb = join(tmp, 'wb', 'cases')
    store(a, 'c1', { 'result.json': JSON.stringify({ gcode: join(ra, 'c1', 'out.gcode') }), 'order.txt': '1 2 3' })
    store(b, 'c1', { 'result.json': JSON.stringify({ gcode: join(rb, 'c1', 'out.gcode') }), 'order.txt': '1 3 2' })
    const d = folderDifferences({
      golden: { store: a, cases: [{ id: 'c1', runs: [run(['order.txt', 'result.json'])] }], root: ra, resources: join(tmp, 'wa', 'res'), work: join(tmp, 'wa') },
      check: { store: b, cases: [{ id: 'c1', runs: [run(['order.txt', 'result.json'])] }], root: rb, resources: join(tmp, 'wb', 'res'), work: join(tmp, 'wb') },
    })
    expect(d.compared).toBe(5)
    expect(d.sites).toEqual([{ case: 'c1', run: 0, output: 'files/order.txt', detail: 'differs between the folders' }])
  })

  test('withHSites makes H the class of a site and keeps the rest', () => {
    const outputs: OutputRecord[] = [
      { case: 'c1', run: 0, output: 'files/order.txt', class: 'B', flags: ['B'], details: {} },
      { case: 'c1', run: 0, output: 'exit', class: 'T', flags: ['T'], details: { T: 't' } },
    ]
    const out = withHSites(outputs, [{ case: 'c1', run: 0, output: 'files/order.txt', detail: 'd' }])
    expect(out[0]).toMatchObject({ class: 'H', flags: ['H'], details: { H: 'd' } })
    expect(out[1]).toMatchObject({ class: 'T', flags: ['T'] })
    expect(withHSites(out, [])[0]).toMatchObject({ class: 'B', flags: ['B'] })
  })
})

describe('envelope', () => {
  test('a line with the same text around its numbers gives each number its spread', () => {
    expect(lineShape('G1 X10.5 Y-2 E.25')).toEqual({ skeleton: 'G# X# Y# E#', numbers: [1, 10.5, -2, 0.25] })
    const e = outputEnvelope({ case: 'c', run: 0, output: 'files/out.gcode' }, [B('G1 X10.5 Y2\nM84\n'), B('G1 X10.25 Y2\nM84\n'), B('G1 X10.75 Y2\nM84\n')])
    expect(e.kind).toBe('text')
    expect(e.varyingLines).toBe(1)
    expect(e.lines).toEqual([{ line: 1, distinct: 3, numbers: [{ field: 1, min: 10.25, max: 10.75, spread: 0.5 }] }])
  })

  test('a line whose text varies is kept as text; a binary output as sizes and differing bytes', () => {
    const e = outputEnvelope({ case: 'c', run: 0, output: 'stdout' }, [B('a\n'), B('b\n')])
    expect(e.lines).toEqual([{ line: 1, distinct: 2, texts: ['a', 'b'] }])
    const z = outputEnvelope({ case: 'c', run: 0, output: 'files/x.3mf' }, [B('PK\u0003\u0004ab'), B('PK\u0003\u0004ac')])
    expect(z).toMatchObject({ kind: 'binary', sizes: [6, 6], differingBytes: [0, 1] })
    expect(outputEnvelope({ case: 'c', run: 0, output: 'x' }, [B('a'), undefined]).kind).toBe('missing')
  })
})
